# ------------ observability (non-`-api`; needs raw stem) --------------------

# `[meta] tenant_id` of the manifest the launcher already derived for
# this pod (BOSS_TENANT_MANIFEST_TOML, from BOSS_TENANT_DIR in
# services-launcher.sh; the compose file names it directly). Empty
# when nothing names one or the file has no id —
# and empty is NOT the brewery. Same read as tenant-launch.sh's
# tenant_id_of, which chooses the seed script by it.
tenant_id() {
    local f="${BOSS_TENANT_MANIFEST_TOML:-}"
    [[ -n "$f" && -f "$f" ]] || return 0
    sed -n 's/^tenant_id *= *"\([^"]*\)".*/\1/p' "$f" | head -1
}

# NATS aggregator + /api/snapshot endpoint for the /ops dashboard.
# Ships /etc/boss-observability.toml (no `-api` suffix).
#
# demo-agents-brewery-only (backlog b03f38de, car 1 of e2580840):
# [demo_agents] is the BREWERY playground's — synthetic telemetry so
# /ops shows what agent oversight looks like before a real
# boss-cybernetics is wired in. Written unconditionally until
# 2026-09-17, it ran in prod too: the demo loop ticked "Hop sourcing
# scout" spend figures into the log every 8 s and /api/snapshot
# answered demo_mode:true for a tenant that is not the brewery. Now the
# block is written only when the tenant IS the brewery; every other
# tenant (and a pod that names none) gets the real aggregator path,
# which boss-observability takes when the block is absent. Populate
# [[vms]] to attach a real boss-cybernetics deployment.
{
    cat <<EOF
# Generated by infra/oss-quickstart/generate-configs.sh
bind = "0.0.0.0:${PORT[observability]}"
nats_url = "$NATS_URL"
EOF
    if [[ "$(tenant_id)" == "brewery" ]]; then
        cat <<EOF

# Synthetic agents: the brewery playground's demo mode (see the
# generator). Absent for every other tenant.
[demo_agents]
tick_seconds = 8
EOF
    fi
} > "$ETC_DIR/boss-observability.toml"
echo "  wrote $ETC_DIR/boss-observability.toml"

