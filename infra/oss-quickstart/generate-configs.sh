# ------------ observability (non-`-api`; needs raw stem) --------------------

# The demo roster the tenant ships, as an absolute path, or nothing.
# The tenant directory is the one the launcher already derived the
# manifest from (BOSS_TENANT_MANIFEST_TOML, from BOSS_TENANT_DIR in
# services-launcher.sh; the compose file names it directly), at either
# spelling the contract accepts: `<dir>/tenant.toml` or
# `<dir>/seeds/tenant.toml`. The roster is `<dir>/seeds/demo_agents.toml`
# (docs/tenant-contract.md). Empty when nothing names a manifest, the
# manifest is unreadable, or the tenant ships no roster.
demo_roster() {
    local f="${BOSS_TENANT_MANIFEST_TOML:-}" dir
    [[ -n "$f" && -f "$f" ]] || return 0
    dir="$(cd "$(dirname "$f")" && pwd)"
    if [[ "$(basename "$dir")" == "seeds" ]]; then
        dir="$(dirname "$dir")"
    fi
    [[ -f "$dir/seeds/demo_agents.toml" ]] || return 0
    echo "$dir/seeds/demo_agents.toml"
}

# NATS aggregator + /api/snapshot endpoint for the /ops dashboard.
# Ships /etc/boss-observability.toml (no `-api` suffix).
#
# demo-agents-brewery-only (backlog b03f38de, car 1 of e2580840):
# [demo_agents] is a PLAYGROUND's — synthetic telemetry so /ops shows
# what agent oversight looks like before a real boss-cybernetics is
# wired in. Written unconditionally until 2026-09-17, it ran in prod
# too: the demo loop ticked "Hop sourcing scout" spend figures into the
# log every 8 s and /api/snapshot answered demo_mode:true for a tenant
# that is not the brewery. From then until 2026-09-23 the block was
# written when the tenant's id was `brewery`.
#
# The switch is now the tenant's own roster file (backlog 1c68aebc): the
# demo agents moved out of the Tier 1 crate that renders them into
# examples/brewery/seeds/demo_agents.toml, and the block names that
# file. A tenant that ships no roster (and a pod that names no tenant)
# gets no block, so boss-observability takes the real aggregator path.
# Populate [[vms]] to attach a real boss-cybernetics deployment.
roster="$(demo_roster)"
{
    cat <<EOF
# Generated by infra/oss-quickstart/generate-configs.sh
bind = "0.0.0.0:${PORT[observability]}"
nats_url = "$NATS_URL"
EOF
    if [[ -n "$roster" ]]; then
        cat <<EOF

# Synthetic agents: the tenant ships a demo roster (see the generator).
# Absent for every tenant that does not.
[demo_agents]
roster = "$roster"
tick_seconds = 8
EOF
    fi
} > "$ETC_DIR/boss-observability.toml"
echo "  wrote $ETC_DIR/boss-observability.toml"

