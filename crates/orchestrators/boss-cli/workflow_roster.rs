//! Pure compiler-input projection shared by the build and image compatibility.

/// This deliberately absent path reruns identity stamping on every Cargo build.
pub const IDENTITY_RERUN_TRIGGER: &str = ".boss-built-from-is-recomputed-every-build";

pub fn render(names: &[String]) -> Result<String, &'static str> {
    let mut kinds = names
        .iter()
        .filter_map(|name| name.strip_suffix(".toml"))
        .collect::<Vec<_>>();
    kinds.sort_unstable();
    if kinds.is_empty() {
        return Err("workflow directory contains no kinds");
    }
    if kinds.windows(2).any(|pair| pair[0] == pair[1])
        || kinds.iter().any(|kind| {
            kind.is_empty()
                || kind
                    .chars()
                    .any(|c| c.is_control() || c == '/' || c == '\\')
        })
    {
        return Err("workflow roster contains malformed or duplicate names");
    }
    let mut out = String::from(
        "// @generated by build.rs from infra/platform/workflows/*.toml — do not edit.\n\
         /// Every workflow kind the PRODUCT ships, by file name: one\n\
         /// definition, the directory (build.rs).\n\
         const PLATFORM_WORKFLOW_KINDS: &[&str] = &[\n",
    );
    for kind in kinds {
        out.push_str(&format!("    {kind:?},\n"));
    }
    out.push_str("];\n");
    Ok(out)
}
