    /// A volume and replica in the shape the rebuild verb's patterns admit.
    const PVC: &str = "pvc-0a1b2c3d-0000-4000-8000-00000000abcd";
    const REPLICA: &str = "pvc-0a1b2c3d-0000-4000-8000-00000000abcd-r-1234abcd";

    fn plan_packet(verb: &str, args: Value, execute: Value) -> Value {
        json!({
            "kind": "ops-request",
            "metadata": {"host": "forge", "verb": verb, "args": args},
            "steps": [{"spec_slug": "filed", "status": "completed"}, execute],
        })
    }

    fn answered(exit: &str) -> Value {
        json!({"spec_slug": "execute", "status": "completed",
               "metadata": {"disposition": "answered", "exit_code": exit, "output": "PLAN"}})
    }

    /// A plan is read off the packet alone: the write that names its
    /// verb, its host and args, and only once the runner answered exit 0.
    #[test]
    fn a_plan_reads_as_its_write_only_once_it_rendered_clean() {
        let v = shipped_allowlist().expect("the verb files parse");
        let args = json!([PVC, REPLICA]);
        match read_plan(
            &v,
            &plan_packet("plan-a-failed-replica-rebuild", args.clone(), answered("0")),
        ) {
            PlanReading::Fileable(ok) => {
                assert_eq!(ok.verb, "rebuild-a-failed-replica");
                assert_eq!(ok.args, vec![PVC, REPLICA]);
                assert!(ok.requires_approval);
            }
            other => panic!("{other:?}"),
        }
        let pending = json!({"spec_slug": "execute", "status": "ready", "metadata": {}});
        for (execute, says) in [
            (pending, "has not answered"),
            (answered("78"), "exit 78"),
            (
                json!({"spec_slug": "execute", "status": "completed",
                       "metadata": {"disposition": "refused", "output": "outside the allowlist"}}),
                "refused it",
            ),
        ] {
            match read_plan(
                &v,
                &plan_packet("plan-a-failed-replica-rebuild", args.clone(), execute),
            ) {
                PlanReading::Refused { write, why } => {
                    assert_eq!(write, "rebuild-a-failed-replica");
                    assert!(why.contains(says), "{why}");
                }
                other => panic!("{says}: {other:?}"),
            }
        }
        assert!(matches!(
            read_plan(&v, &plan_packet("uptime", json!([]), answered("0"))),
            PlanReading::NotAPlan(_)
        ));
        let mut not_ops = plan_packet("plan-a-pod-reap", json!([]), answered("0"));
        not_ops["kind"] = json!("backlog-item");
        assert!(matches!(read_plan(&v, &not_ops), PlanReading::NotAPlan(_)));
    }
