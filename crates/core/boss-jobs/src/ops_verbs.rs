    /// The compiled-in set IS the directory: the names build.rs generated
    /// equal the `*.json` files under `infra/ops/verbs/` as they stand
    /// now, and each is named by its file. This is the one place the
    /// Rust derivation of "name = file name" is measured against the
    /// shell one (`verbs-allowlist.sh`), because `include_str!` needs
    /// literal paths and so this reader cannot call that script.
    ///
    /// It also catches the shared-target-dir staleness boss-testing's
    /// build.rs documents: a `VERB_FILES` linked from a neighbouring
    /// checkout's build would disagree with this checkout's directory.
    #[test]
    fn the_compiled_in_verbs_are_the_directory() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../infra/ops/verbs");
        let mut on_disk: Vec<String> = std::fs::read_dir(&dir)
            .expect("infra/ops/verbs/ exists")
            .map(|e| e.unwrap().path())
            .filter(|p| p.extension().is_some_and(|x| x == "json"))
            .map(|p| p.file_stem().unwrap().to_string_lossy().into_owned())
            .collect();
        on_disk.sort();
        let mut compiled: Vec<String> = VERB_FILES.iter().map(|(n, _)| (*n).to_string()).collect();
        compiled.sort();
        assert_eq!(
            compiled, on_disk,
            "VERB_FILES is not infra/ops/verbs/*.json — rebuild"
        );
        assert!(
            !dir.join("../verbs.json").exists(),
            "infra/ops/verbs.json is back — the directory is the allowlist (5086842d)"
        );
        for (name, text) in VERB_FILES {
            let spec: Value =
                serde_json::from_str(text).unwrap_or_else(|e| panic!("{name}.json: {e}"));
            assert!(
                spec.is_object() && spec.get("verbs").is_none(),
                "{name}.json must describe ONE verb"
            );
            assert_eq!(
                std::fs::read_to_string(dir.join(format!("{name}.json"))).unwrap(),
                *text,
                "{name}.json on disk differs from the compiled copy"
            );
        }
    }

